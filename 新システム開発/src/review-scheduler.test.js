import {strict as a} from 'node:assert';
import {updateReviewItem,selectDueReviews,consumeReview} from './review-scheduler.js';
import {exportCheckpoint,restoreCheckpoint} from './session-checkpoint.js';
const e={qualificationId:'takken',topicId:'37',unitId:'37-a',source:'wrong',result:'wrong'};
const first=updateReviewItem(null,e,{today:'2026-10-13'}).item;
a.equal(first.dueDate,'2026-10-14');
const early=updateReviewItem(first,{...e,result:'confident_correct'},{today:'2026-10-13'}).item;
a.equal(early.dueDate,'2026-10-14');
const later=updateReviewItem(first,{...e,result:'confident_correct'},{today:'2026-10-14'}).item;
a.equal(later.intervalDays,3);
a.equal(later.dueDate,'2026-10-17');
const fail=updateReviewItem(later,e,{today:'2026-10-17'}).item;
a.equal(fail.intervalDays,1);
a.equal(fail.recallSuccesses,0);
a.equal(updateReviewItem(later,{...e,result:'guess_correct'},{today:'2026-10-17'}).item.intervalDays,3);
a.equal(updateReviewItem(later,{...e,result:'skip'},{today:'2026-10-17'}).item.dueDate,'2026-10-17');
a.equal(selectDueReviews({today:'2026-10-18',items:[later]}).items.length,1);
a.equal(selectDueReviews({today:'2026-10-18',items:[later],explicitTopic:true,practiceSinceReview:1}).items.length,0);
a.equal(selectDueReviews({today:'2026-10-18',items:[later],explicitTopic:true,practiceSinceReview:2}).items.length,1);
const queue={queueId:'r1',unitIds:['37-a'],nextIndex:0,consumedKeys:[]};
a.equal(consumeReview(queue,{unitId:'37-a',attemptId:'1',valid:true,explanationComplete:true,isReinforcement:true}).nextIndex,0);
const consumed=consumeReview(queue,{unitId:'37-a',attemptId:'1',valid:true,explanationComplete:true});
a.equal(consumeReview(consumed,{unitId:'37-a',attemptId:'1',valid:true,explanationComplete:true}).nextIndex,1);
const json=exportCheckpoint({qualificationId:'takken',topicId:'37',ledger:[{attemptId:'1'}],reviewItems:[later],reviewQueue:consumed,usedOfficialKeys:['takken:2025:regular:general:29'],at:'2026-10-13T17:00:00Z'});
a.equal(restoreCheckpoint(json).reviewQueue.nextIndex,1);
a.throws(()=>restoreCheckpoint('{"version":1}'),/CHECKPOINT_SCHEMA_INVALID/);
console.log('PASS review scheduling and checkpoint tests');
